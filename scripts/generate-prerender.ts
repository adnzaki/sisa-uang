import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { PRERENDERED_PAGES } from '../src/prerender/pages';
import { injectPrerenderedHtml } from '../src/prerender/injector';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const rootDir = path.resolve(__dirname, '..');
const distDir = path.join(rootDir, 'dist');
const indexHtmlPath = path.join(distDir, 'index.html');

function runPrerender() {
  if (!fs.existsSync(indexHtmlPath)) {
    console.error(`[Pre-render] dist/index.html not found. Run "vite build" first.`);
    process.exit(1);
  }

  // 1. Read base template generated by Vite
  const baseTemplate = fs.readFileSync(indexHtmlPath, 'utf8');
  console.log(`[Pre-render] Generating static HTML for public & legal pages...`);

  // 2. Save clean un-injected SPA app shell as app-shell.html
  const appShellPath = path.join(distDir, 'app-shell.html');
  const cleanAppShell = baseTemplate.replace(/<div id="app">[\s\S]*?<\/div>/i, '<div id="app"></div>');
  fs.writeFileSync(appShellPath, cleanAppShell, 'utf8');

  let count = 0;

  // 3. Inject root landing page into dist/index.html so that visiting https://domain/ directly gets full pre-rendered HTML
  const landingPageData = PRERENDERED_PAGES['/'] || PRERENDERED_PAGES['/landing'];
  if (landingPageData) {
    const rootHtml = injectPrerenderedHtml(baseTemplate, landingPageData);
    fs.writeFileSync(indexHtmlPath, rootHtml, 'utf8');
    count++;
    console.log(`✓ Pre-rendered ROOT: / -> dist/index.html (${Math.round(rootHtml.length / 1024)} KB)`);
  }

  // 4. Generate all sub-routes (dist/[route]/index.html)
  for (const [routePath, pageData] of Object.entries(PRERENDERED_PAGES)) {
    const cleanRoute = routePath.replace(/^\//, '');
    if (!cleanRoute) continue; // Already generated as dist/index.html

    const routeFolder = path.join(distDir, cleanRoute);
    if (!fs.existsSync(routeFolder)) {
      fs.mkdirSync(routeFolder, { recursive: true });
    }

    const outputHtml = injectPrerenderedHtml(baseTemplate, pageData);
    const targetFile = path.join(routeFolder, 'index.html');
    fs.writeFileSync(targetFile, outputHtml, 'utf8');
    count++;
    console.log(`✓ Pre-rendered: ${routePath} -> dist/${cleanRoute}/index.html (${Math.round(outputHtml.length / 1024)} KB)`);
  }

  // Ensure /landing directory also contains the landing page
  const landingFolder = path.join(distDir, 'landing');
  if (!fs.existsSync(landingFolder)) {
    fs.mkdirSync(landingFolder, { recursive: true });
  }
  if (landingPageData) {
    const landingHtml = injectPrerenderedHtml(baseTemplate, landingPageData);
    fs.writeFileSync(path.join(landingFolder, 'index.html'), landingHtml, 'utf8');
  }

  console.log(`[Pre-render] Successfully generated ${count} pre-rendered static HTML pages in dist/.`);
}

runPrerender();

function ssgPrerenderPlugin() {
  return {
    name: 'vite-plugin-sisauang-ssg-prerender',
    closeBundle() {
      const distDir = path.resolve(__dirname, 'dist');
      const indexHtmlPath = path.join(distDir, 'index.html');
      if (!fs.existsSync(indexHtmlPath)) return;

      // 1. Read clean, untouched SPA shell generated by Vite (with empty <div id="app"></div>)
      const cleanShell = fs.readFileSync(indexHtmlPath, 'utf8');

      // 2. Save pristine SPA app shell as app-shell.html (guaranteed NO prerendered landing page content)
      const appShellPath = path.join(distDir, 'app-shell.html');
      fs.writeFileSync(appShellPath, cleanShell, 'utf8');

      // 3. Generate all sub-routes from the clean SPA shell
      for (const [routePath, pageData] of Object.entries(PRERENDERED_PAGES)) {
        const cleanRoute = routePath.replace(/^\//, '');
        if (!cleanRoute) continue;

        const folder = path.join(distDir, cleanRoute);
        if (!fs.existsSync(folder)) {
          fs.mkdirSync(folder, { recursive: true });
        }
        const outputHtml = injectPrerenderedHtml(cleanShell, pageData);
        fs.writeFileSync(path.join(folder, 'index.html'), outputHtml, 'utf8');
      }

      // 4. Ensure /landing directory also contains the landing page
      const landingData = PRERENDERED_PAGES['/'] || PRERENDERED_PAGES['/landing'];
      if (landingData) {
        const landingFolder = path.join(distDir, 'landing');
        if (!fs.existsSync(landingFolder)) {
          fs.mkdirSync(landingFolder, { recursive: true });
        }
        fs.writeFileSync(path.join(landingFolder, 'index.html'), injectPrerenderedHtml(cleanShell, landingData), 'utf8');

        // 5. Inject landing page into dist/index.html for root GET / requests
        const rootHtml = injectPrerenderedHtml(cleanShell, landingData);
        fs.writeFileSync(indexHtmlPath, rootHtml, 'utf8');
      }
    },
  };
}

